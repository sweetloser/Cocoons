import Foundation

struct SourceStringProtector {
    struct Result {
        let source: String
        let protectedCount: Int
        let warnings: [String]
    }

    private struct Replacement {
        let range: NSRange
        let declaration: String
        let helper: String
    }

    private let options: ProcessingOptions

    init(options: ProcessingOptions) {
        self.options = options
    }

    func transform(source: String, relativePath: String) throws -> Result {
        guard options.protectAnnotatedStrings else {
            return Result(source: source, protectedCount: 0, warnings: [])
        }

        var replacements = try cStringReplacements(
            source: source,
            relativePath: relativePath
        )

        if ["m", "mm"].contains(URL(fileURLWithPath: relativePath).pathExtension.lowercased()) {
            replacements += try objectiveCStringReplacements(
                source: source,
                relativePath: relativePath
            )
        }

        guard !replacements.isEmpty else {
            return Result(source: source, protectedCount: 0, warnings: [])
        }

        let mutable = NSMutableString(string: source)
        var helpers: [String] = []

        for replacement in replacements.sorted(by: { $0.range.location > $1.range.location }) {
            mutable.replaceCharacters(in: replacement.range, with: replacement.declaration)
            helpers.append(replacement.helper)
        }

        mutable.append("\n\n/* Generated by Cocoons. */\n")
        mutable.append(helpers.reversed().joined(separator: "\n\n"))
        mutable.append("\n")

        return Result(
            source: mutable as String,
            protectedCount: replacements.count,
            warnings: []
        )
    }

    private func cStringReplacements(
        source: String,
        relativePath: String
    ) throws -> [Replacement] {
        let marker = #"(?:__attribute__\s*\(\(\s*annotate\s*\(\s*"(?:obfuscate|cocoons:str)"\s*\)\s*\)\)|\bOBF\b)"#
        let pattern = marker
            + #"\s*((?:static\s+)?)(const\s+char\s+)([A-Za-z_][A-Za-z0-9_]*)\s*(\[\s*\]|\*)\s*=\s*"((?:\\.|[^"\\])*)"\s*;"#
        let regex = try NSRegularExpression(pattern: pattern, options: [.anchorsMatchLines])
        let text = source as NSString

        return regex.matches(
            in: source,
            range: NSRange(location: 0, length: text.length)
        ).compactMap { match in
            guard
                let storageClass = capture(match, 1, in: text),
                let name = capture(match, 3, in: text),
                let shape = capture(match, 4, in: text),
                let literal = capture(match, 5, in: text)
            else {
                return nil
            }

            var bytes = decodeCString(literal)
            bytes.append(0)
            let symbol = generatedSymbol(relativePath: relativePath, name: name, literal: literal)
            let key = UInt8(truncatingIfNeeded: stableHash(symbol) | 1)
            let encrypted = encrypt(bytes, key: key)
            let initializer = encrypted.map { String(format: "0x%02x", $0) }.joined(separator: ", ")

            if shape.contains("*") {
                let storage = "cocoons_storage_\(symbol)"
                let declaration = """
                static unsigned char \(storage)[] = { \(initializer) };
                \(storageClass)const char *\(name) = (const char *)\(storage);
                """
                let helper = decodeHelper(
                    symbol: symbol,
                    storageExpression: storage,
                    countExpression: "sizeof(\(storage))",
                    key: key,
                    completion: nil
                )
                return Replacement(range: match.range, declaration: declaration, helper: helper)
            }

            let declaration = "\(storageClass)char \(name)[] = { \(initializer) };"
            let helper = decodeHelper(
                symbol: symbol,
                storageExpression: name,
                countExpression: "sizeof(\(name))",
                key: key,
                completion: nil
            )
            return Replacement(range: match.range, declaration: declaration, helper: helper)
        }
    }

    private func objectiveCStringReplacements(
        source: String,
        relativePath: String
    ) throws -> [Replacement] {
        let marker = #"(?:__attribute__\s*\(\(\s*annotate\s*\(\s*"(?:obfuscate|cocoons:str)"\s*\)\s*\)\)|\bOBF\b)"#
        let pattern = marker
            + #"\s*((?:static\s+)?)NSString\s*\*\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*@"((?:\\.|[^"\\])*)"\s*;"#
        let regex = try NSRegularExpression(pattern: pattern, options: [.anchorsMatchLines])
        let text = source as NSString

        return regex.matches(
            in: source,
            range: NSRange(location: 0, length: text.length)
        ).compactMap { match in
            guard
                let storageClass = capture(match, 1, in: text),
                let name = capture(match, 2, in: text),
                let literal = capture(match, 3, in: text)
            else {
                return nil
            }

            var bytes = decodeCString(literal)
            bytes.append(0)
            let symbol = generatedSymbol(relativePath: relativePath, name: name, literal: literal)
            let storage = "cocoons_storage_\(symbol)"
            let key = UInt8(truncatingIfNeeded: stableHash(symbol) | 1)
            let encrypted = encrypt(bytes, key: key)
            let initializer = encrypted.map { String(format: "0x%02x", $0) }.joined(separator: ", ")
            let declaration = """
            static unsigned char \(storage)[] = { \(initializer) };
            \(storageClass)NSString *\(name) = nil;
            """
            let assignment = """
            \(name) = [[NSString alloc] initWithBytes:\(storage)
                                               length:sizeof(\(storage)) - 1
                                             encoding:NSUTF8StringEncoding];
            """
            let helper = decodeHelper(
                symbol: symbol,
                storageExpression: storage,
                countExpression: "sizeof(\(storage))",
                key: key,
                completion: assignment
            )
            return Replacement(range: match.range, declaration: declaration, helper: helper)
        }
    }

    private func decodeHelper(
        symbol: String,
        storageExpression: String,
        countExpression: String,
        key: UInt8,
        completion: String?
    ) -> String {
        let completionBody = completion.map { "\n    \($0.replacingOccurrences(of: "\n", with: "\n    "))" } ?? ""
        return """
        __attribute__((constructor))
        static void cocoons_decode_\(symbol)(void) {
            unsigned char *bytes = (unsigned char *)\(storageExpression);
            for (unsigned long i = 0; i < \(countExpression); ++i) {
                bytes[i] ^= (unsigned char)(0x\(String(format: "%02x", key))u ^ ((i * 0x33u) & 0xffu));
            }\(completionBody)
        }
        """
    }

    private func capture(
        _ match: NSTextCheckingResult,
        _ index: Int,
        in text: NSString
    ) -> String? {
        let range = match.range(at: index)
        guard range.location != NSNotFound else { return nil }
        return text.substring(with: range)
    }

    private func generatedSymbol(relativePath: String, name: String, literal: String) -> String {
        String(format: "%016llx", stableHash("\(relativePath)|\(name)|\(literal)|\(options.deterministicSeed)"))
    }

    private func stableHash(_ value: String) -> UInt64 {
        value.utf8.reduce(1_469_598_103_934_665_603) { hash, byte in
            (hash ^ UInt64(byte)) &* 1_099_511_628_211
        }
    }

    private func encrypt(_ bytes: [UInt8], key: UInt8) -> [UInt8] {
        bytes.enumerated().map { index, byte in
            byte ^ (key ^ UInt8(truncatingIfNeeded: index &* 0x33))
        }
    }

    private func decodeCString(_ literal: String) -> [UInt8] {
        var result: [UInt8] = []
        var index = literal.startIndex

        while index < literal.endIndex {
            let character = literal[index]
            guard character == "\\" else {
                result.append(contentsOf: String(character).utf8)
                index = literal.index(after: index)
                continue
            }

            index = literal.index(after: index)
            guard index < literal.endIndex else {
                result.append(UInt8(ascii: "\\"))
                break
            }

            let escaped = literal[index]
            switch escaped {
            case "n": result.append(0x0a)
            case "r": result.append(0x0d)
            case "t": result.append(0x09)
            case "0": result.append(0x00)
            case "\\": result.append(UInt8(ascii: "\\"))
            case "\"": result.append(UInt8(ascii: "\""))
            default: result.append(contentsOf: String(escaped).utf8)
            }
            index = literal.index(after: index)
        }
        return result
    }
}
